#!/usr/bin/env python3
"""Generate every AI/IDE adapter file from AGENTS.md so they never drift.

    python3 tools/build_adapters.py

Writes into adapters/ and adapters/MANIFEST (read by all installers).
MANIFEST line format:  <mode> <source-in-repo> <destination-in-project>
  mode = merge  → insert/replace a marked NoCap block inside an existing file
  mode = copy   → copy file (overwrite)
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "adapters")
agents = open(os.path.join(ROOT, "AGENTS.md"), encoding="utf-8").read()


def section(title):
    m = re.search(rf"^## {re.escape(title)}.*?$(.*?)(?=^## |\Z)", agents, re.S | re.M)
    return m.group(1).strip()


commands = section("1. Commands").replace("`prompts/", "`.nocap/prompts/")
guard = section("2. Always-on guard rules (apply to EVERY piece of code you write)")

CORE = f"""# NoCap (documentation + security guard)

This project uses **NoCap**. Full instructions: `.nocap/AGENTS.md`. Read it before running any command below.

## Commands
{commands}

## Always-on guard rules
{guard}

Generated docs go to `docs/` using templates in `.nocap/templates/`. Findings use the format in `.nocap/AGENTS.md` §4.
"""

COMMANDS = {
    "docs": ("01-full-documentation", "Generate or refresh the full documentation set in docs/"),
    "audit": ("02-security-audit", "Full security audit with standard fixes → docs/SECURITY_AUDIT.md"),
    "threat-model": ("03-threat-model", "STRIDE + LINDDUN threat model → docs/THREAT_MODEL.md"),
    "compliance": ("04-compliance", "Compliance gap analysis (gdpr, dpdp, hipaa, pci, soc2, iso27001, ccpa, wcag, ai-act, all)"),
    "review": ("05-code-review", "Secure code review of a file, folder or the current diff"),
    "fix": ("06-fix", "Fix audit findings, critical first, with tests"),
    "architecture": ("07-architecture", "Architecture & design docs with C4/Mermaid diagrams"),
    "explain": ("08-explain", "Explain the codebase for a new developer → docs/ONBOARDING.md"),
    "update": ("09-update", "Update docs for code changed since they were last verified"),
    "score": ("10-score", "Compute the NoCap score and badge"),
    "ship": ("11-ship", "Production-readiness GO / NO-GO gate"),
}


def w(rel, text):
    p = os.path.join(A, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as fh:
        fh.write(text)


manifest = [
    "# mode source destination   (generated by tools/build_adapters.py — do not edit by hand)",
]

# Universal AGENTS.md (Codex, Cursor, Copilot agent, Zed, Jules, Amp, Aider w/ read:, Roo, Factory, …)
w("generic/AGENTS.md", CORE)
manifest.append("merge adapters/generic/AGENTS.md AGENTS.md")

# Claude Code
w("claude/CLAUDE.md", "@.nocap/AGENTS.md\n\n" + CORE)
manifest.append("merge adapters/claude/CLAUDE.md CLAUDE.md")
for name, (pf, desc) in COMMANDS.items():
    w(f"claude/commands/nocap-{name}.md",
      f"---\ndescription: NoCap — {desc}\nargument-hint: [optional target or framework]\n---\n"
      f"Run the NoCap `{name}` workflow.\n\nFollow `.nocap/prompts/{pf}.md` exactly, together with the rules in "
      f"`.nocap/AGENTS.md`.\nTarget / arguments: $ARGUMENTS\n")
    manifest.append(f"copy adapters/claude/commands/nocap-{name}.md .claude/commands/nocap-{name}.md")

# Cursor
w("cursor/nocap.mdc", "---\ndescription: NoCap documentation & security guard rules\nglobs:\nalwaysApply: true\n---\n" + CORE)
manifest.append("copy adapters/cursor/nocap.mdc .cursor/rules/nocap.mdc")

# GitHub Copilot (instructions + reusable prompt files)
w("copilot/copilot-instructions.md", CORE)
manifest.append("merge adapters/copilot/copilot-instructions.md .github/copilot-instructions.md")
for name, (pf, desc) in COMMANDS.items():
    w(f"copilot/prompts/nocap-{name}.prompt.md",
      f"---\ndescription: NoCap — {desc}\n---\nFollow [the NoCap {name} workflow](../../.nocap/prompts/{pf}.md) "
      f"and the rules in [AGENTS.md](../../.nocap/AGENTS.md).\n")
    manifest.append(f"copy adapters/copilot/prompts/nocap-{name}.prompt.md .github/prompts/nocap-{name}.prompt.md")

# Windsurf
w("windsurf/nocap.md", "---\ntrigger: always_on\ndescription: NoCap documentation & security guard rules\n---\n" + CORE)
manifest.append("copy adapters/windsurf/nocap.md .windsurf/rules/nocap.md")

# Cline / Roo Code / Continue / Kilo
w("cline/nocap.md", CORE)
manifest.append("copy adapters/cline/nocap.md .clinerules/nocap.md")
manifest.append("copy adapters/cline/nocap.md .roo/rules/nocap.md")
w("continue/nocap.md", "---\nname: NoCap\nalwaysApply: true\n---\n" + CORE)
manifest.append("copy adapters/continue/nocap.md .continue/rules/nocap.md")

# Gemini CLI / Gemini Code Assist
w("gemini/GEMINI.md", CORE)
manifest.append("merge adapters/gemini/GEMINI.md GEMINI.md")

# JetBrains Junie
w("junie/guidelines.md", CORE)
manifest.append("merge adapters/junie/guidelines.md .junie/guidelines.md")

# Aider
w("aider/.aider.conf.yml", "# NoCap: load the agent instructions into every Aider session\nread:\n  - .nocap/AGENTS.md\n")
manifest.append("copy-if-missing adapters/aider/.aider.conf.yml .aider.conf.yml")

# CI workflow template (installed with --ci)
w("ci/nocap.yml", """# NoCap — runs on every push / PR. Fails the build on high or critical findings.
name: NoCap
on:
  push:
    branches: [main]
  pull_request:
permissions:
  contents: read
jobs:
  nocap:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: sanket-manohar/nocap@v1
        with:
          fail-on: high        # critical | high | medium | low | none
""")

with open(os.path.join(A, "MANIFEST"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(manifest) + "\n")
print(f"Built {len(manifest) - 1} adapter targets.")
